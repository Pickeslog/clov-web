// '1' 과 '#' 둘 다 채움으로 본다 — 글리프는 0/1, 손으로 그린 도형은 ./# 가 읽기 쉽다.
const isOn = (ch) => ch === '1' || ch === '#'

const rects = (rows, fill, offsetX = 0) => rows.flatMap((row, y) => (
  [...row].map((bit, x) => (isOn(bit)
    ? <rect key={`${offsetX + x}-${y}`} x={offsetX + x} y={y} width="1" height="1" fill={fill} />
    : null))
))

const svgProps = (w, h, scale, title) => ({
  viewBox: `0 0 ${w} ${h}`,
  width: w * scale,
  height: h * scale,
  shapeRendering: 'crispEdges',
  role: title ? 'img' : 'presentation',
  'aria-label': title,
  'aria-hidden': title ? undefined : 'true',
})

/** 영문 라벨. scale 은 "픽셀 하나를 화면 몇 px 로 그릴지". */
export function PixelText({ text, scale = 3, fill = 'currentColor', className, title }) {
  const chars = [...text].map((ch) => GLYPHS[ch]).filter(Boolean).map((g) => g.split(','))
  const gap = 1
  const width = Math.max(0, chars.reduce((w, g) => w + g[0].length + gap, 0) - gap)

  let cx = 0
  const shapes = chars.flatMap((glyph) => {
    const out = rects(glyph, fill, cx)
    cx += glyph[0].length + gap
    return out
  })

  return <svg className={className} {...svgProps(width, 7, scale, title)}>{shapes}</svg>
}

/** 임의의 픽셀 도형. rows 는 '.'/'#'(또는 0/1) 문자열 배열. */
export function PixelArt({ rows, scale = 4, fill = 'currentColor', className, title }) {
  return (
    <svg className={className} {...svgProps(rows[0].length, rows.length, scale, title)}>
      {rects(rows, fill)}
    </svg>
  )
}

/** 클로버 마크. 모서리 장식·배경 워터마크·"모두 동등" 그림에 쓴다. */
export function PixelClover({ scale = 3, fill = 'currentColor', className }) {
  return <PixelArt rows={CLOVER} scale={scale} fill={fill} className={className} />
}

/** 골드 동전. */
export function PixelCoin({ scale = 4, fill = 'currentColor', className, title }) {
  return <PixelArt rows={COIN} scale={scale} fill={fill} className={className} title={title} />
}
